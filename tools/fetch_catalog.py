"""Rebuild ui/game-catalog.mjs: the names the game's packets do not carry.

The game sends tickets, items and servers by number only. This reads the public game database that
Questlog serves (four requests: tickets with their caps and refill rules, item names, buffs, servers with
their short tags, plus buff names with which ones take control away) and writes them as one reviewed module, so Luma needs no network at run time.
Names belong to NCSOFT; the data's provenance is recorded in docs/reference-data.md.

    python tools/fetch_catalog.py            # fetch and write ui/game-catalog.mjs
    python tools/fetch_catalog.py --check    # fetch and say whether the file is out of date
"""
import argparse
import json
import pathlib
import sys
import urllib.parse
import urllib.request

BASE = "https://questlog.gg/aion-2/api/trpc"
TARGET = pathlib.Path(__file__).resolve().parents[1] / "ui" / "game-catalog.mjs"
# Global regions first: the same server number is reused by the Korean and Taiwanese services.
REGIONS = ("eu", "nae", "naw", "la", "as", "ko", "tw")


def fetch(path, payload=None):
    url = f"{BASE}/{path}"
    if payload is not None:
        url += "?input=" + urllib.parse.quote(json.dumps(payload, separators=(",", ":")))
    request = urllib.request.Request(url, headers={"User-Agent": "luma-dps catalog refresh (+local)"})
    with urllib.request.urlopen(request, timeout=120) as response:
        return json.load(response)["result"]["data"]


def tickets(raw):
    rows = {}
    for key, row in raw.items():
        if not isinstance(row, dict) or not str(row.get("name", "")).strip():
            continue
        entry = {"name": row["name"].strip(), "max": int(row.get("max") or 0)}
        if row.get("memberMax"):
            entry["memberMax"] = int(row["memberMax"])
        refill = row.get("refill")
        if isinstance(refill, dict) and refill.get("every") and refill.get("amount"):
            entry["refill"] = {
                "from": str(refill.get("from", "")),
                "every": int(refill["every"]),
                "amount": int(refill["amount"]),
                "memberAmount": int(refill.get("memberAmount") or refill["amount"]),
            }
        rows[int(key)] = entry
    return dict(sorted(rows.items()))


def items(raw):
    return {int(key): row["name"].strip() for key, row in sorted(raw.items(), key=lambda pair: int(pair[0])) if isinstance(row, dict) and str(row.get("name", "")).strip()}


def buffs(raw):
    """The effects worth naming: those the game shows, and every one that takes control away."""
    rows = {}
    for key, row in raw.items():
        if not isinstance(row, dict) or not str(row.get("name", "")).strip():
            continue
        control = row.get("control") or 0
        if row.get("shown") or control:
            rows[int(key)] = [row["name"].strip(), control, 1 if row.get("debuff") else 0]
    return dict(sorted(rows.items()))


def servers(raw):
    rows = {}
    for region in REGIONS:
        for row in raw:
            if row.get("region") == region and row.get("serverId") and row.get("shortName"):
                rows.setdefault(int(row["serverId"]), [row["name"], row["shortName"]])
    return dict(sorted(rows.items()))


def render(ticket_rows, item_rows, server_rows, buff_rows=None):
    def block(name, rows):
        lines = [f"  {key}: {json.dumps(value, ensure_ascii=False, separators=(',', ':'))}," for key, value in rows.items()]
        body = "\n".join(lines) + "\n" if lines else ""
        return f"export const {name} = Object.freeze({{\n" + body + "});\n"

    head = (
        "// Generated by tools/fetch_catalog.py from the public game database Questlog serves; do not edit.\n"
        "// The names are NCSOFT's. Provenance: docs/reference-data.md.\n"
        "// TICKETS: name, the most a ticket holds (and with membership), and how it refills.\n"
        "// ITEMS: item number to name. SERVERS: server number to [name, short tag].\n"
        "// BUFFS: effect number to [name, the control it applies (0 for none), 1 for a debuff].\n"
    )
    return head + block("TICKETS", ticket_rows) + "\n" + block("ITEMS", item_rows) + "\n" + block("SERVERS", server_rows) + "\n" + block("BUFFS", buff_rows or {})


def build():
    names = fetch("combatLog.entities.names", {"language": "en"})
    buff_rows = buffs(fetch("combatLog.entities.buffs", {"language": "en"}))
    return render(tickets(fetch("combatLog.entities.tickets", {"language": "en"})), items(names["item"]), servers(fetch("armory.getServers")), buff_rows)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    text = build()
    if parser.parse_args().check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        print("up to date" if current == text else "out of date")
        return 0 if current == text else 1
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
