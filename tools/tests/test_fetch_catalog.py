import importlib.util
import json
from pathlib import Path
import unittest

SPEC = importlib.util.spec_from_file_location("luma_fetch_catalog", Path(__file__).resolve().parents[1] / "fetch_catalog.py")
fetch_catalog = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(fetch_catalog)


class CatalogTests(unittest.TestCase):
    def test_tickets_keep_names_caps_and_refill_and_drop_rows_without_a_name(self):
        rows = fetch_catalog.tickets({
            "60000001": {"name": " Odyle Energy ", "max": 560, "memberMax": 840, "refill": {"from": "daily-reset", "every": 10800, "amount": 15, "memberAmount": 15}},
            "3": {"name": "Lower Abyss Access Hours", "max": 0},
            "9": {"name": "  ", "max": 5},
            "11": "not a row",
        })
        self.assertEqual(list(rows), [3, 60000001])
        self.assertEqual(rows[60000001], {"name": "Odyle Energy", "max": 560, "memberMax": 840, "refill": {"from": "daily-reset", "every": 10800, "amount": 15, "memberAmount": 15}})
        self.assertEqual(rows[3], {"name": "Lower Abyss Access Hours", "max": 0})

    def test_items_are_sorted_by_number_and_nameless_ones_are_dropped(self):
        rows = fetch_catalog.items({"930100003": {"name": "Abyss Points"}, "5": {"name": "Five"}, "6": {"name": ""}, "7": {}})
        self.assertEqual(rows, {5: "Five", 930100003: "Abyss Points"})
        self.assertEqual(list(rows), [5, 930100003])

    def test_global_servers_win_over_the_korean_and_taiwanese_reuse_of_a_number(self):
        rows = fetch_catalog.servers([
            {"region": "tw", "serverId": 1001, "name": "Taiwan One", "shortName": "TW1"},
            {"region": "ko", "serverId": 1001, "name": "Korea One", "shortName": "KO1"},
            {"region": "eu", "serverId": 2315, "name": "Zemurru", "shortName": "ZEM"},
            {"region": "eu", "serverId": 2316, "name": "No tag", "shortName": ""},
        ])
        self.assertEqual(rows, {1001: ["Korea One", "KO1"], 2315: ["Zemurru", "ZEM"]})

    def test_buffs_keep_the_shown_ones_and_every_one_that_takes_control_away(self):
        rows = fetch_catalog.buffs({
            "100": {"name": "Stun", "control": "stun", "shown": False, "debuff": True},
            "101": {"name": "Hidden helper", "shown": False},
            "102": {"name": " Defense Increase ", "shown": True},
            "103": {"name": "", "shown": True},
            "104": "not a row",
        })
        self.assertEqual(rows, {100: ["Stun", "stun", 1], 102: ["Defense Increase", 0, 0]})

    def test_the_rendered_module_is_valid_javascript_data_with_every_name_escaped(self):
        text = fetch_catalog.render({3: {"name": 'A "quoted" name', "max": 0}}, {5: "Ludra's Blade\\Edge"}, {2315: ["Zemurru", "ZEM"]})
        self.assertTrue(text.startswith("// Generated by tools/fetch_catalog.py"))
        for name in ("TICKETS", "ITEMS", "SERVERS"):
            self.assertIn(f"export const {name} = Object.freeze({{", text)
        self.assertIn(json.dumps("Ludra's Blade\\Edge", ensure_ascii=False), text)
        self.assertIn('{"name":"A \\"quoted\\" name","max":0}', text)
        with_buffs = fetch_catalog.render({}, {}, {}, {100: ["Stun", "stun", 1]})
        self.assertIn('export const BUFFS = Object.freeze({\n  100: ["Stun","stun",1],', with_buffs)
        self.assertIn("export const BUFFS = Object.freeze({\n});", text)


if __name__ == "__main__":
    unittest.main()
