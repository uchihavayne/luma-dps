"""Rebuild ui/assets/icons and ui/game-icons.mjs: the game's own icons for skills, effects, tickets
and currencies.

Which icon belongs to which id comes from the same public game database as the name catalog
(see fetch_catalog.py). Each icon is downloaded once from the CDN that database uses, shrunk to 64 x 64
and kept as a small WebP next to the UI, so Luma needs no network at run time. The artwork belongs to
NCSOFT; provenance and the terms caveat are in docs/reference-data.md.

    python tools/fetch_icons.py            # download what is missing and rewrite ui/game-icons.mjs
    python tools/fetch_icons.py --refresh  # download everything again
"""
import argparse
import io
import json
import pathlib
import sys
import time
import urllib.request

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import fetch_catalog  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[1]
FOLDER = ROOT / "ui" / "assets" / "icons"
MODULE = ROOT / "ui" / "game-icons.mjs"
CDN = "https://cdn.questlog.gg/aion-2"
SIZE = 64
# Larger pictures the interface shows big: the Hidden Cube as the game draws it, gold and red. The CDN
# serves these under their own file names (no repeated name to strip).
EXTRAS = {
    "cube_gold": ("/assets/Game/UI/Resource/Texture/Item/ETC/P_Img_HiddenCube_01.webp", 128),
    "cube_red": ("/assets/Game/UI/Resource/Texture/Item/ETC/P_Img_HiddenCube_01_V04.webp", 128),
}


def key_of(path):
    """/assets/.../Icon_abysspoint.Icon_abysspoint -> icon_abysspoint (a file name that is safe anywhere)."""
    name = path.rsplit("/", 1)[-1].split(".", 1)[0].lower()
    return "".join(char if char.isalnum() or char in "_-" else "_" for char in name)


def url_of(path):
    """The CDN serves the asset under its path with the repeated name replaced by .webp."""
    stem, _, _ = path.rpartition(".")
    return f"{CDN}{stem}.webp"


def collect(skills, buffs, tickets, items, wanted_items):
    """id -> icon path for each family, dropping rows without a usable icon path."""
    def usable(path):
        return isinstance(path, str) and path.startswith("/assets/") and "." in path.rsplit("/", 1)[-1]

    return {
        "skills": {int(key): row["icon"] for key, row in skills.items() if isinstance(row, dict) and usable(row.get("icon"))},
        "buffs": {int(key): row["icon"] for key, row in buffs.items() if isinstance(row, dict) and (row.get("shown") or row.get("control")) and usable(row.get("icon"))},
        "tickets": {int(key): row["icon"] for key, row in tickets.items() if isinstance(row, dict) and usable(row.get("icon"))},
        "items": {int(key): row["icon"] for key, row in items.items() if int(key) in wanted_items and isinstance(row, dict) and usable(row.get("icon"))},
    }


def render(families, files, extras=None):
    """The module: ICONS lists the file keys once, each family maps an id to a position in it."""
    extras = extras or {}
    order = sorted(set(files) | set(extras))
    position = {key: index for index, key in enumerate(order)}
    head = (
        "// Generated by tools/fetch_icons.py from the public game database Questlog serves; do not edit.\n"
        "// The artwork is NCSOFT's. Provenance: docs/reference-data.md.\n"
        "// ICONS: the files in assets/icons (as <name>.webp). Each family maps an id to a position in ICONS.\n"
    )
    body = f"export const ICONS = Object.freeze({json.dumps(order, separators=(',', ':'))});\n"
    for name in ("skills", "buffs", "tickets", "items"):
        rows = {key: position[key_of(path)] for key, path in sorted(families[name].items()) if key_of(path) in position}
        lines = [f"  {key}: {index}," for key, index in rows.items()]
        body += f"\nexport const {name.upper()}_ICONS = Object.freeze({{\n" + ("\n".join(lines) + "\n" if lines else "") + "});\n"
    body += "\nexport const EXTRA_ICONS = Object.freeze({\n" + "".join(f"  {name}: {position[name]},\n" for name in sorted(extras) if name in position) + "});\n"
    return head + body


def download(path, size=SIZE, url=None):
    from PIL import Image  # Pillow, only needed here

    request = urllib.request.Request(url or url_of(path), headers={"User-Agent": "luma-dps icon refresh (+local)"})
    with urllib.request.urlopen(request, timeout=60) as response:
        picture = Image.open(io.BytesIO(response.read())).convert("RGBA")
    picture.thumbnail((size, size), Image.LANCZOS)
    out = io.BytesIO()
    picture.save(out, "WEBP", quality=82, method=6)
    return out.getvalue()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--refresh", action="store_true")
    refresh = parser.parse_args().refresh
    names = fetch_catalog.fetch("combatLog.entities.names", {"language": "en"})
    wanted = {int(key) for key in names["item"] if int(key) // 1000 == 930_100} | {512_000_014}
    families = collect(
        fetch_catalog.fetch("combatLog.entities.skills", {"language": "en"}),
        fetch_catalog.fetch("combatLog.entities.buffs", {"language": "en"}),
        fetch_catalog.fetch("combatLog.entities.tickets", {"language": "en"}),
        names["item"],
        wanted,
    )
    paths = {}
    for rows in families.values():
        for path in rows.values():
            paths.setdefault(key_of(path), path)
    FOLDER.mkdir(parents=True, exist_ok=True)
    files, missing = {}, []
    for index, (key, path) in enumerate(sorted(paths.items())):
        target = FOLDER / f"{key}.webp"
        if refresh or not target.exists():
            try:
                target.write_bytes(download(path))
                time.sleep(0.03)
            except Exception as error:  # a missing icon is left out, not fatal
                missing.append(f"{key}: {error}")
                continue
        files[key] = path
        if index % 100 == 0:
            print(f"{index}/{len(paths)}", flush=True)
    extras = {}
    for key, (path, size) in EXTRAS.items():
        target = FOLDER / f"{key}.webp"
        try:
            if refresh or not target.exists():
                target.write_bytes(download(path, size, f"{CDN}{path}"))
            extras[key] = path
        except Exception as error:
            missing.append(f"{key}: {error}")
    MODULE.write_text(render(families, files, extras), encoding="utf-8", newline="\n")
    size = sum(path.stat().st_size for path in FOLDER.glob("*.webp"))
    print(f"{len(files)} icons ({size} bytes), {len(missing)} missing")
    for line in missing[:20]:
        print("  missing", line)
    return 0


if __name__ == "__main__":
    sys.exit(main())
